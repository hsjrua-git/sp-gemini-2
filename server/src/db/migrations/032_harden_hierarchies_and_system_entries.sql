-- Hierarchy and system-journal hardening discovered by the post-remediation
-- audit. These are database guarantees so concurrent API requests cannot race
-- past application pre-checks.

CREATE TABLE hierarchy_invariant_locks (
  key text PRIMARY KEY
);

INSERT INTO hierarchy_invariant_locks (key) VALUES
  ('student_groups'),
  ('acct_accounts')
ON CONFLICT DO NOTHING;

CREATE FUNCTION student_groups_hierarchy_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM hierarchy_invariant_locks
   WHERE key = 'student_groups'
   FOR UPDATE;

  IF NEW.parent_id IS NOT NULL AND EXISTS (
    WITH RECURSIVE ancestors AS (
      SELECT id, parent_id
      FROM student_groups
      WHERE id = NEW.parent_id
      UNION
      SELECT g.id, g.parent_id
      FROM student_groups g
      JOIN ancestors a ON g.id = a.parent_id
    )
    SELECT 1 FROM ancestors WHERE id = NEW.id
  ) THEN
    RAISE EXCEPTION 'student group hierarchy cannot contain a cycle'
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.parent_id IS NOT NULL
     AND NEW.archived_at IS NULL
     AND EXISTS (
       SELECT 1 FROM student_groups
       WHERE id = NEW.parent_id AND archived_at IS NOT NULL
     ) THEN
    RAISE EXCEPTION 'an active group cannot be placed under an archived group'
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.archived_at IS NOT NULL
     AND EXISTS (
       SELECT 1 FROM student_groups
       WHERE parent_id = NEW.id AND archived_at IS NULL
     ) THEN
    RAISE EXCEPTION 'a group with active children cannot be archived'
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER student_groups_hierarchy_guard_trg
  BEFORE INSERT OR UPDATE ON student_groups
  FOR EACH ROW EXECUTE FUNCTION student_groups_hierarchy_guard();

CREATE FUNCTION acct_accounts_hierarchy_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  PERFORM 1 FROM hierarchy_invariant_locks
   WHERE key = 'acct_accounts'
   FOR UPDATE;

  IF NEW.parent_id IS NOT NULL AND EXISTS (
    WITH RECURSIVE ancestors AS (
      SELECT id, parent_id
      FROM acct_accounts
      WHERE id = NEW.parent_id
      UNION
      SELECT a.id, a.parent_id
      FROM acct_accounts a
      JOIN ancestors p ON a.id = p.parent_id
    )
    SELECT 1 FROM ancestors WHERE id = NEW.id
  ) THEN
    RAISE EXCEPTION 'account hierarchy cannot contain a cycle'
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

CREATE TRIGGER acct_accounts_hierarchy_guard_trg
  BEFORE INSERT OR UPDATE OF parent_id ON acct_accounts
  FOR EACH ROW EXECUTE FUNCTION acct_accounts_hierarchy_guard();

-- Opening and closing entries are generated by fiscal workflows, not ordinary
-- user journals. Letting accounting.post void them bypasses accounting.close
-- and makes the once-ever opening impossible to recreate.
CREATE FUNCTION acct_system_entries_not_voided() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status = 'posted'
     AND NEW.status = 'voided'
     AND OLD.source_type IN ('opening', 'closing') THEN
    RAISE EXCEPTION '% journal entries cannot be voided', OLD.source_type
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER acct_system_entries_not_voided_trg
  BEFORE UPDATE OF status ON acct_journal_entries
  FOR EACH ROW EXECUTE FUNCTION acct_system_entries_not_voided();

